ll modpow(ll x, ll n, ll m) {
    if (n == 0) return 1%m;
    long long u = modpow(x,n/2,m);
    u = (u*u)%m;
    if (n%2 == 1) u = (u*x)%m;
    return u;
}

void solve() {
    ll rows, columns, r ,c;
    cin >> rows >> columns >> r >> c;

    ll power = ((rows*columns)-((rows-r+1))*((columns-c+1)));

    cout << modpow(2, power, MOD) << "\n";
}



