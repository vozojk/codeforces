void solve() {

    int n,h,l;
    cin >> n >> h >> l;
    vector<int> nums;
    int cnt = n;
    int borderline = 0;
    for (int i = 0; i < n; i++) {
        int a;
        cin >> a;
        if (a>max(h,l))continue;
        if (a>min(h,l))borderline++;
        nums.push_back(a);
    }
    int sz = nums.size();
    int res = -1;
    if (borderline>sz/2)res = sz-borderline;
    else res = sz/2;
    cout << res << "\n";


}

