void solve() {
 
    int n, x;
    cin >> n >> x;
 
    vector<ll> dp(x+10, INF);
    vector<int> coins(n);
    for (int i = 0; i < n; i++) {
        cin >> coins[i];
    }
    dp[0]=0;
    for (int i = 0; i <= x; i++) {
        for (int a : coins) {
            if (i-a<0)continue;
            dp[i] = min(dp[i], dp[i-a]+1);
        }
    }
    if (dp[x]==INF)cout << -1;
    else cout << dp[x];
}
 
int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
 
 
    int t = 1;
    //cin >> t;
 
    while(t--) {
        solve();
    }
 
    return 0;
}